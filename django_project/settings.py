# Decisión de ingeniería (U2-1): USE_TZ = False.
#
# Con USE_TZ = True y TIME_ZONE local, el ORM genera CONVERT_TZ() con zonas
# horarias NOMBRADAS ('UTC' -> 'America/Santiago') para las extracciones de
# fecha del Django Admin (date_hierarchy y el filtro por fecha). MySQL NO
# trae las tablas de zonas horarias cargadas de fábrica (hay que cargarlas
# a mano con `mysql_tzinfo_to_sql /usr/share/zoneinfo | mysql -u root mysql`),
# de modo que CONVERT_TZ devuelve NULL y los changelists de Track y Playlist
# caen con error 500 ("Database returned an invalid datetime value").
#
# Con USE_TZ = False las fechas se guardan y muestran en hora local de
# Santiago directamente, sin CONVERT_TZ: el proyecto funciona igual en un
# MySQL recién instalado en Windows, macOS o Linux (requisito de la
# entrega: config reproducible, sin pasos manuales extra del servidor).
USE_TZ = False


