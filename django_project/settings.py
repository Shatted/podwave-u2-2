# --- Carga de variables de entorno desde .env (sin dependencias) ----------
# En desarrollo las variables pueden vivir en un archivo .env junto a
# manage.py (ver .env.example). Esta función lo carga SIN instalar
# python-dotenv: parsea líneas KEY=VALUE y las fija solo si la variable
# aún no existe en el entorno (las variables reales del entorno ganan).
def _cargar_env(ruta):
    try:
        with open(ruta, encoding='utf-8') as archivo:
            for linea in archivo:
                linea = linea.strip()
                if not linea or linea.startswith('#') or '=' not in linea:
                    continue
                clave, _, valor = linea.partition('=')
                clave = clave.strip()
                valor = valor.strip().strip('"').strip("'")
                if clave:
                    os.environ.setdefault(clave, valor)
    except OSError:
        pass  # sin archivo .env: se usan solo las variables del entorno


_cargar_env(BASE_DIR / '.env')


def _variable(nombre, requerida=True, por_defecto=None):
    """Lee una variable de entorno; falla rápido si es obligatoria."""
    valor = os.environ.get(nombre)
    if valor is None or valor == '':
        if requerida:
            raise ImproperlyConfigured(
                f'Falta la variable de entorno {nombre}. '
                f'Copia .env.example a .env y complétala (instrucción 9: '
                f'credenciales fuera del código).')
        return por_defecto
    return valor


